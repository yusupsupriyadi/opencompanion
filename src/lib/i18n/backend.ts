/** A backend message as the screen shows it in `lang`. Unknown text and English pass through. */
export function translateBackend(text: string, lang: string): string {
  if (lang !== "id" || !text) return text;
  for (const [re, out] of RULES) {
    if (re.test(text)) return text.replace(re, out);
  }
  return text;
}
